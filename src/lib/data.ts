const SLUG: Record<string, string> = {
  СВ: "sv",
  ДИА: "diag",
  ДОИ: "out",
  БЛ: "mid",
  ЛИБ: "lib",
};

const clamp = (n: number, min = 40, max = 99) => Math.max(min, Math.min(max, Math.round(n)));

function makePlayer(raw: RawPlayer, teamId: string, index: number, teamPrestige: number): Player {
  const [name, posCode, number, age, height, overall, country = "Россия"] = raw;
  const pos = POS_BY_CODE[posCode];
  const jitter = ((index * 7 + number * 3) % 5) - 2;
  const attackBonus =
    posCode === "ДИА" ? 4 : posCode === "ДОИ" ? 1 : posCode === "БЛ" ? -5 : posCode === "СВ" ? -11 : -19;
  const blockBonus =
    posCode === "БЛ" ? 5 : posCode === "СВ" ? -8 : posCode === "ЛИБ" ? -18 : -2;
  const serveBonus =
    posCode === "ДИА" ? 2 : posCode === "СВ" ? 1 : posCode === "ЛИБ" ? -14 : -1;
  const receiveBonus =
    posCode === "ЛИБ" ? 5 : posCode === "ДОИ" ? 2 : posCode === "СВ" ? -1 : -12;
  const defenseBonus =
    posCode === "ЛИБ" ? 4 : posCode === "ДОИ" ? 1 : posCode === "БЛ" ? -9 : -5;
  const settingBonus =
    posCode === "СВ" ? 7 : posCode === "ДИА" || posCode === "ДОИ" ? -15 : -23;
  const potential = clamp(
    overall + (age <= 23 ? 7 : age <= 27 ? 3 : age <= 31 ? 1 : 0) + (index % 2),
    overall,
    97,
  );
  const rawValue =
    Math.pow(Math.max(0, overall - 74), 2) * 0.34 +
    Math.max(0, 32 - age) * 2.4 +
    (potential - overall) * 1.1;
  const value = Math.max(2.5, Math.round(rawValue * 10) / 10);
  return {
    id: `${teamId}-${index}-${SLUG[posCode]}${number}`,
    name,
    teamId,
    pos,
    posCode,
    number,
    age,
    height,
    country,
    flag: FLAGS[country] || "🌍",
    overall,
    potential,
    form: 6 + ((index * 3 + number) % 4),
    fitness: 88 + ((index * 5 + number) % 12),
    morale: 78 + ((index * 9 + teamPrestige) % 16),
    attack: clamp(overall + attackBonus + (jitter % 3)),
    block: clamp(overall + blockBonus + (index % 3)),
    serve: clamp(overall + serveBonus + ((number + index) % 3)),
    receive: clamp(overall + receiveBonus + (jitter % 2)),
    defense: clamp(overall + defenseBonus + (index % 2)),
    setting: clamp(overall + settingBonus + (index % 2)),
    salary: Math.round(((overall - 70) * 0.55 + 2.4) * 10) / 10,
    contract: 1 + ((index + number) % 3),
    starter: false,
    value,
    listed: index >= 10 || teamId === "free",
    askingPrice: Math.round(value * 1.06 * 10) / 10,
    stats: { matches: 0, sets: 0, points: 0, attacks: 0, aces: 0, blocks: 0, mvp: 0 },
  };
}

export function createPlayers(): Player[] {
  const players: Player[] = [];
  for (const team of TEAMS) {
    const roster = ROSTERS[team.id] || [];
    roster.forEach((raw, index) => {
      players.push(makePlayer(raw, team.id, index, team.prestige));
    });
  }
  FREE_AGENTS.forEach((raw, index) => {
    players.push(makePlayer(raw, "free", index, 76));
  });
  return assignDefaultStarters(players);
}

export function assignDefaultStarters(players: Player[]): Player[] {
  const next = players.map((p) => ({ ...p }));
  for (const team of [...TEAMS, { id: "free" }]) {
    const squad = next.filter((p) => p.teamId === team.id && !p.listed);
    const byPos = (pos: Pos) => squad.filter((p) => p.pos === pos).sort((a, b) => b.overall - a.overall);
    const slots: Player[] = [
      ...byPos("Связующий").slice(0, 1),
      ...byPos("Диагональный").slice(0, 1),
      ...byPos("Доигровщик").slice(0, 2),
      ...byPos("Блокирующий").slice(0, 2),
      ...byPos("Либеро").slice(0, 1),
    ];
    const ids = new Set(slots.map((p) => p.id));
    squad.forEach((p) => {
      const found = next.find((x) => x.id === p.id);
      if (found) found.starter = ids.has(found.id);
    });
  }
  return next;
}

